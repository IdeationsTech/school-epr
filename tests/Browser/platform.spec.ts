import {test,expect} from '@playwright/test';
test('provider onboards a school, receives a partial payment and suspends access',async({page})=>{
    await page.goto('/admin');
    await page.getByLabel('Email address').fill('platform@example.test');
    await page.getByLabel('Password',{exact:true}).fill('BrowserTestPassword123!');
    await page.getByRole('button',{name:'Sign in',exact:true}).click();
    await expect(page.getByRole('heading',{name:'Platform overview',exact:true})).toBeVisible();
    await page.getByRole('navigation').getByRole('button',{name:'Packages',exact:true}).click();
    await page.getByLabel('name',{exact:true}).fill('Pilot Package');
    await page.getByLabel('code',{exact:true}).fill('PILOT');
    await page.getByLabel('monthly_price',{exact:true}).fill('5000');
    await page.getByLabel('annual_price',{exact:true}).fill('50000');
    await page.getByRole('button',{name:'Save package'}).click();
    await expect(page.getByRole('status')).toHaveText('Package saved.');
    await page.getByRole('navigation').getByRole('button',{name:'Schools',exact:true}).click();
    await page.getByRole('button',{name:'Add school',exact:true}).click();
    await page.getByLabel('School name',{exact:true}).fill('Pilot Academy');
    await page.getByLabel('School code',{exact:true}).fill('PILOT-SCHOOL');
    await page.getByLabel('Phone',{exact:true}).pressSequentially('3001234567');
    await page.getByLabel('Address',{exact:true}).fill('12 Pilot Road, Lahore');
    await page.getByLabel('Owner name',{exact:true}).fill('Pilot Owner');
    await page.getByLabel('Owner email',{exact:true}).fill('pilotowner@example.test');
    await page.getByLabel('Initial password',{exact:true}).fill('PilotOwnerPassword123!');
    await page.getByLabel('Confirm password',{exact:true}).fill('PilotOwnerPassword123!');
    await page.getByLabel('Package',{exact:true}).selectOption({label:'Pilot Package · 1000 students / 2 campuses'});
    const date=new Date();const start=new Intl.DateTimeFormat('en-CA',{timeZone:'Asia/Karachi',year:'numeric',month:'2-digit',day:'2-digit'}).format(date);
    date.setUTCFullYear(date.getUTCFullYear()+1);const end=date.toISOString().slice(0,10);
    await page.getByLabel('Starts on',{exact:true}).fill(start);
    await page.getByLabel('Ends on',{exact:true}).fill(end);
    await page.getByRole('button',{name:'Create school & owner'}).click();
    await expect(page.getByRole('heading',{name:'School details',exact:true})).toBeVisible();
    await expect(page.getByRole('heading',{name:'Pilot Academy',exact:true})).toBeVisible();
    await page.reload();
    await expect(page.getByRole('heading',{name:'Pilot Academy',exact:true})).toBeVisible();
    await page.getByLabel('Invoice',{exact:true}).selectOption({index:1});
    await page.getByLabel('Amount (PKR)',{exact:true}).fill('2000');
    await page.getByLabel('Transaction / receipt reference',{exact:true}).fill('BANK-PILOT-001');
    await page.getByRole('button',{name:'Record payment',exact:true}).click();
    await expect(page.getByRole('status')).toHaveText('Payment recorded.');
    await expect(page.getByText('partial',{exact:true})).toBeVisible();
    await page.screenshot({path:'test-results/platform-school-desktop.png',fullPage:true});
    await expect(page.getByText(/^LIC-/)).toBeVisible();
    await page.getByRole('button',{name:'Print invoice',exact:true}).click();
    await expect(page.getByRole('dialog',{name:'Billing document'})).toBeVisible();
    await page.getByRole('button',{name:'Close document',exact:true}).click();
    await page.getByRole('navigation').getByRole('button',{name:'School licenses',exact:true}).click();
    await expect(page.getByRole('heading',{name:'School licenses',level:1})).toBeVisible();
    await page.getByRole('navigation').getByRole('button',{name:'Service billing',exact:true}).click();
    await expect(page.getByRole('row').filter({hasText:'Pilot Academy'})).toBeVisible();
    await page.getByRole('navigation').getByRole('button',{name:'Provider profile',exact:true}).click();
    await page.getByLabel('Provider name',{exact:true}).fill('ERP Service Company');
    await page.getByLabel('Provider email',{exact:true}).fill('service@example.test');
    await page.getByLabel('Provider address',{exact:true}).fill('12 Provider Road, Lahore');
    await page.getByLabel('Phone',{exact:true}).pressSequentially('3001234567');
    await page.getByRole('button',{name:'Save provider profile',exact:true}).click();
    await expect(page.getByRole('status')).toHaveText('Provider profile saved.');
    await page.getByRole('navigation').getByRole('button',{name:'Support',exact:true}).click();
    await page.getByRole('button',{name:'New ticket',exact:true}).click();
    await page.getByLabel('Find school for ticket').fill('Pilot Academy');
    await page.getByLabel('Ticket school',{exact:true}).selectOption({label:'Pilot Academy'});
    await page.getByLabel('Ticket subject').fill('License setup question');
    await page.getByLabel('Description',{exact:true}).fill('Please review the new school setup.');
    await page.getByRole('button',{name:'Save support ticket',exact:true}).click();
    await expect(page.getByText('License setup question',{exact:true})).toBeVisible();
    await page.getByRole('button',{name:'Open ticket',exact:true}).click();
    await page.getByLabel('Ticket status').selectOption('resolved');
    await page.getByLabel('Support reply').fill('Setup is confirmed.');
    await page.getByRole('button',{name:'Save support ticket',exact:true}).click();
    await page.getByRole('navigation').getByRole('button',{name:'Audit log',exact:true}).click();
    await expect(page.getByRole('heading',{name:'Audit log',level:1})).toBeVisible();
    await page.getByRole('navigation').getByRole('button',{name:'Schools',exact:true}).click();
    await page.getByRole('row').filter({hasText:'Pilot Academy'}).getByRole('button',{name:/Manage/}).click();
    await page.getByLabel('Control action reason',{exact:true}).fill('Pilot service paused by provider');
    await page.getByLabel('License access status',{exact:true}).selectOption('suspended');
    await page.getByRole('button',{name:'Apply license status',exact:true}).click();
    await expect(page.getByRole('status')).toHaveText('License status updated.');
    await page.setViewportSize({width:390,height:844});
    await expect(page.locator('.sidebar')).toHaveCSS('transform','matrix(1, 0, 0, 1, -260, 0)');
    expect(await page.evaluate(()=>document.documentElement.scrollWidth)).toBeLessThanOrEqual(390);
    await page.screenshot({path:'test-results/platform-school-mobile.png',fullPage:true});
    await page.getByRole('button',{name:'Sign out',exact:true}).click();
    await page.getByLabel('Email address').fill('pilotowner@example.test');
    await page.getByLabel('Password',{exact:true}).fill('PilotOwnerPassword123!');
    await page.getByRole('button',{name:'Sign in',exact:true}).click();
    await expect(page.getByRole('alert')).toContainText('inactive');
});
